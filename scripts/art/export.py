"""Writes src/client/cast-art.ts, the character screen's tiles: each portrait as a palette and a character a pixel.

Needs: pip install pillow. Run from this folder: python export.py
"""
import gzip
import importlib
import os
import sys
CH = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
out = []
total = []
for name in ['marine', 'ninja', 'astro', 'xeno', 'hunter']:  # ROLE's order
    im = importlib.import_module(name).draw().im
    cols = []
    s = ''
    for y in range(64):
        for x in range(64):
            r, g, b, a = im.getpixel((x, y))
            if not a:
                s += ' '
                continue
            h = '%02x%02x%02x' % (r, g, b)
            if h not in cols:
                cols.append(h)
            s += CH[cols.index(h)]
    out.append((name, cols, s))
    total.append(len(cols))
ts = '''// Generated by scripts/art/export.py from the hand-drawn pixel art (the user, 2026-11-26): each class's tile on the character
// screen, 64 x 64, in ROLE's order. A palette of #rrggbb colours, then one character a pixel, row by
// row from the top: a space is transparent, a letter the palette's colour at its place in ART_KEYS.
export const ART_KEYS = '%s';
export const ART: readonly (readonly [palette: string, pixels: string])[] = [
''' % CH
for name, cols, s in out:
    ts += '  // %s\n  [\n    %r,\n    %r,\n  ],\n' % (name.capitalize(), ''.join(cols), s)
ts += '];\n'
dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'client', 'cast-art.ts')
open(dst, 'w').write(ts)
print('colours', total, 'gzip', len(gzip.compress(ts.encode(), 9)))
