"""The announcer's lines, spoken by Kokoro-82M (Apache-2.0) and encoded into one sprite.

Writes src/client/voice/clips.ts (the lines, their words for the screen and where each lies in the
sprite), opus.ts and mp3.ts
(the sprite as base64: Ogg Opus first, MP3 for the browsers that cannot decode it).

Needs: pip install kokoro-onnx soundfile numpy; brew install espeak-ng opus-tools lame; the model
files kokoro-v1.0.onnx and voices-v1.0.bin from
https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0 in the working directory.

    python scripts/voice.py path/to/model/dir
"""
import base64, os, subprocess, sys, tempfile
import numpy as np
import soundfile as sf
from kokoro_onnx import EspeakConfig, Kokoro

# Calm and unhurried: the most natural of Kokoro's voices, a tenth slower than its pace.
VOICE, SPEED = "af_heart", 0.9
LINES = [
    ("START", "The match begins."),
    ("MINUTE", "One minute remaining."),
    ("TAKEN", "We have their flag."),
    ("STOLEN", "They have our flag."),
    ("BACK", "Our flag is back."),
    ("GONE", "Their flag is back."),
    ("SCORE", "We score."),
    ("CONCEDE", "They score."),
    ("WIN", "Victory."),
    ("LOSS", "Defeat."),
    ("DRAW", "A draw."),
    ("AIM", "Impressive!"),
    # The own frags: the first of the match, by the fists, in quick succession, in a row.
    ("FIRST", "First blood!"),
    ("HUMILIATION", "Humiliation!"),
    ("DOUBLE", "Double kill!"),
    ("MULTI", "Multi kill!"),
    ("MEGA", "Mega kill!"),
    ("ULTRA", "Ultra kill!"),
    ("MONSTER", "Monster kill!"),
    ("SPREE", "Killing spree!"),
    ("RAMPAGE", "Rampage!"),
    ("DOMINATING", "Dominating!"),
    ("UNSTOPPABLE", "Unstoppable!"),
    ("GODLIKE", "Godlike!"),
]
RATE = 24000
GAP = int(RATE * 0.25)
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "client", "voice")

models = sys.argv[1] if len(sys.argv) > 1 else "."
brew = subprocess.run(["brew", "--prefix"], capture_output=True, text=True).stdout.strip()
kokoro = Kokoro(
    os.path.join(models, "kokoro-v1.0.onnx"),
    os.path.join(models, "voices-v1.0.bin"),
    espeak_config=EspeakConfig(
        lib_path=f"{brew}/lib/libespeak-ng.dylib", data_path=f"{brew}/share/espeak-ng-data"
    ),
)

parts, clips, t = [], [], GAP
for key, text in LINES:
    a, sr = kokoro.create(text, voice=VOICE, speed=SPEED, lang="en-us")
    assert sr == RATE
    loud = np.where(np.abs(a) > 0.01 * np.abs(a).max())[0]
    a = a[max(loud[0] - RATE // 100, 0) : loud[-1] + RATE // 20]
    a = (a / np.abs(a).max() * 0.9).astype(np.float32)
    clips.append((key, text, t, len(a)))
    parts += [a, np.zeros(GAP, np.float32)]
    t += len(a) + GAP
sprite = np.concatenate([np.zeros(GAP, np.float32)] + parts)

with tempfile.TemporaryDirectory() as tmp:
    wav = os.path.join(tmp, "voice.wav")
    sf.write(wav, sprite, RATE)
    encoded = {}
    for ext, cmd in [
        ("opus", ["opusenc", "--quiet", "--speech", "--bitrate", "16", wav]),
        ("mp3", ["lame", "--quiet", "-m", "m", "-b", "32", wav]),
    ]:
        dst = os.path.join(tmp, f"voice.{ext}")
        subprocess.run(cmd + [dst], check=True)
        encoded[ext] = open(dst, "rb").read()

head = "// Generated by scripts/voice.py: do not edit.\n"
for ext, data in encoded.items():
    with open(os.path.join(OUT, f"{ext}.ts"), "w") as f:
        f.write(head + f"/** The announcer's sprite, {ext.upper()} as base64 ({len(data)} B). */\n")
        f.write(f"export default '{base64.b64encode(data).decode()}';\n")
with open(os.path.join(OUT, "clips.ts"), "w") as f:
    f.write(head)
    f.write("/** The announcer's lines, by name: an index into CLIPS. */\nexport const LINE = {\n")
    for i, (key, text, _, _) in enumerate(clips):
        f.write(f"  /** \"{text}\" */\n  {key}: {i},\n")
    f.write("} as const;\n\n")
    # The awards (the lines that end in "!") are shown too; the rest have their own banners.
    f.write("/** The words of each award, for the screen, separated by | (the other lines' are empty). */\n")
    said = "|".join(text if text.endswith("!") else "" for _, text, _, _ in clips)
    f.write(f"const AWARDS =\n  '{said}';\nexport const SAID = AWARDS.split('|');\n\n")
    f.write("/** Where each line lies in the sprite: its start and its length, seconds. */\n")
    f.write("export const CLIPS: readonly (readonly [number, number])[] = [\n")
    for _, _, start, n in clips:
        f.write(f"  [{round(start / RATE, 3)!r}, {round(n / RATE, 3)!r}],\n")
    f.write("];\n")
print({k: len(v) for k, v in encoded.items()}, f"{len(sprite) / RATE:.1f} s")
