export interface PlayerInfo {
  id: number;
  name: string;
  /** CSS colour, unique within the room. */
  color: string;
}

/** Bits of Input.keys. Keys are read by KeyboardEvent.code, so WASD is ZQSD on AZERTY. */
export const KEY = {
  FORWARD: 1,
  BACK: 2,
  LEFT: 4,
  RIGHT: 8,
  JUMP: 16,
  /** Left mouse button: the chaingun fires every FIRE_EVERY steps while held. */
  FIRE: 32,
} as const;

/** One client step: what the player held during 1 / TICK_HZ s, and where they looked. */
export interface Input {
  /** Client step counter, u16, wraps. The host acks the last one it applied. */
  seq: number;
  /** KEY bits. */
  keys: number;
  /** Radians, [0, 2π). */
  yaw: number;
  /** Radians, [-MAX_PITCH, MAX_PITCH]. */
  pitch: number;
  /**
   * Host tick the client drew the others at when it sent this input, fractional (interpolation
   * between two snapshots), in [0, 65536): the host rewinds the targets of a shot to it (lag
   * compensation). The wire keeps 1/256 tick. Absent (no snapshot seen yet): no rewind.
   */
  view?: number;
}

export interface PlayerState {
  id: number;
  /** Feet position. */
  x: number;
  y: number;
  z: number;
  /** Vertical speed, m/s. */
  vy: number;
  yaw: number;
  pitch: number;
  /** Standing on a floor: a jump is allowed. */
  ground: boolean;
  /** Steps until the chaingun may fire again, 0 to FIRE_EVERY. */
  cool: number;
}

/** One shot, as the host resolved it. */
export interface Shot {
  /** The shooter. */
  id: number;
  /** Where the shot stopped: a wall, a floor, a ceiling, a target, or RANGE away. */
  x: number;
  y: number;
  z: number;
  /** Id of the player hit, -1 for the level or nothing. */
  hit: number;
}

/** Procedural textures, generated by the client. A sector names one per surface. */
export const TEX = {
  BRICK: 0,
  TILE: 1,
  LAVA: 2,
  STONE: 3,
} as const;

/**
 * A room, Doom style: a convex polygon on the floor plane with a flat floor and a flat ceiling.
 * Two sectors are joined where one has the edge a→b and the other b→a with the very same
 * coordinates (a portal); every other edge is a solid wall. Split an edge with collinear points
 * when several sectors meet it (no T-junctions).
 */
export interface Sector {
  /**
   * Corners as (x, z), counter-clockwise: the signed area Σ (x_i z_{i+1} - x_{i+1} z_i) is positive.
   * Collinear points are allowed.
   */
  pts: [x: number, z: number][];
  /** Heights in metres, ceil > floor. */
  floor: number;
  ceil: number;
  /** TEX ids of the floor, the walls (and steps) on its edges, and the ceiling. */
  ft: number;
  wt: number;
  ct: number;
  /** Light level multiplied into the shading, 0 to 1. Absent: 1. */
  light?: number;
}

export interface MapDef {
  sectors: Sector[];
  /** Spawn points: feet x, z (inside a sector, standing on its floor) and the yaw to face. */
  spawns: [x: number, z: number, yaw: number][];
}

/** One directed edge of a sector, see compile in level.ts. */
export interface Edge {
  ax: number;
  az: number;
  bx: number;
  bz: number;
  /** Index of the sector the edge belongs to (the side it faces into). */
  front: number;
  /** Index of the sector across a portal, -1 for a solid wall. */
  back: number;
}

/** A map ready for physics and drawing. */
export interface Level {
  map: MapDef;
  /** Every edge of every sector, in sector then point order. */
  edges: Edge[];
}

/** One player in a snapshot. */
export interface SnapPlayer {
  id: number;
  x: number;
  y: number;
  z: number;
  vy: number;
  yaw: number;
  pitch: number;
  ground: boolean;
  cool: number;
  /** Seq of the last input of this player the host applied: the client replays the ones after. */
  ack: number;
}

export interface Snapshot {
  /** Host tick, u16, wraps. */
  tick: number;
  players: SnapPlayer[];
  /** Shots fired since the previous snapshot, in order. */
  shots: Shot[];
}

/** Room rules, set by the host. Defaults in constants.ts (RULES). */
export interface Rules {
  maxPlayers: number;
}

/**
 * The subset of WebSocket the client relies on. A real WebSocket (with
 * binaryType 'arraybuffer') and the local BroadcastChannel socket both fit.
 */
export interface SocketLike {
  binaryType: string;
  onopen: (() => void) | null;
  onclose: (() => void) | null;
  onmessage: ((ev: { data: string | ArrayBuffer }) => void) | null;
  send(data: string | ArrayBuffer): void;
  close(): void;
}

/** Calls cb every ms milliseconds until the returned function is called. */
export type Every = (cb: () => void, ms: number) => () => void;

/** One connected peer, as the room sees it. Transport-agnostic. */
export interface Conn {
  send(data: string | ArrayBuffer): void;
}
